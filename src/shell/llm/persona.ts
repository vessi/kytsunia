export type PersonaOptions = {
  // ID моделі, якою відповідає Кицюня, наприклад "claude-haiku-4-5-20251001".
  model: string;
  // Модель дайджесту. Якщо вона інша — Кицюня чесно каже, що дайджести пише не вона сама.
  digestModel?: string;
  visionEnabled: boolean;
  digestEnabled: boolean;
  searchEnabled: boolean;
  // Текст характеру замість PERSONA_PROMPT — персона, задана адміном для чату.
  // Технічна частина (модель, вміння) дописується до нього так само.
  character?: string;
};

/**
 * "claude-haiku-4-5-20251001" → "Claude Haiku 4.5", "claude-sonnet-5" → "Claude Sonnet 5".
 * Незнайомий формат повертаємо як є — краще сирий ID, ніж вигадана назва.
 */
export function modelDisplayName(modelId: string): string {
  const m = /^claude-([a-z]+)-(\d+)(?:-(\d+))?(?:-\d{8})?$/.exec(modelId);
  if (!m) return modelId;
  const family = m[1] as string;
  const major = m[2] as string;
  const minor = m[3];
  const version = minor === undefined ? major : `${major}.${minor}`;
  return `Claude ${family[0]?.toUpperCase()}${family.slice(1)} ${version}`;
}

/**
 * Повний system-промпт: характер + чесний опис того, що Кицюня таке і що вміє.
 * Другий блок залежить від конфіга, тому збирається при старті, а не хардкодиться.
 * Результат стабільний протягом життя процесу — кешування префікса не ламає.
 */
export function buildPersonaPrompt(opts: PersonaOptions): string {
  const modelName = modelDisplayName(opts.model);
  const digestName = opts.digestModel ? modelDisplayName(opts.digestModel) : modelName;

  const identity = [
    `- Ти Telegram-бот. Відповіді тобі генерує модель ${modelName} від Anthropic. Якщо питають, яка ти модель, на чому працюєш, чи ти ChatGPT — кажи чесно і саме це, назву пиши латиницею. Не вдавай іншу модель і не кажи, що не знаєш.`,
  ];
  if (opts.digestEnabled && digestName !== modelName) {
    identity.push(`- Дайджести чату за тебе пише ${digestName}.`);
  }

  const abilities = [
    "- Відповідаєш, коли тебе назвали на імʼя, тегнули через @, відповіли на твоє повідомлення або пишуть тобі в особисті.",
    "- Бачиш кілька останніх повідомлень чату і профілі активних учасників. Довготривалої памʼяті немає: попередні розмови не памʼятаєш і запамʼятати щось на потім не можеш.",
  ];
  if (opts.visionEnabled) {
    abilities.push(
      "- Бачиш фото, якщо їх надіслали разом зі зверненням до тебе, відповіли ними в треді з тобою або щойно кинули в чат. Старі фото з історії не бачиш. Якщо фото в розмові немає, про свій зір не згадуй.",
    );
  } else {
    abilities.push("- Фото не бачиш: якщо скинули картинку — скажи, що бачиш лише текст.");
  }
  if (opts.digestEnabled) {
    abilities.push(
      "- Дайджест чату робиш на команду «Кицюня, дайджест» (можна з числом: «Кицюня, дайджест 50»).",
    );
  }
  if (opts.searchEnabled) {
    abilities.push(
      "- В інтернет ходиш лише на команду «Кицюня, пошукай …» (або «Кицюня, пошукай» у відповідь на повідомлення). Це стосується лише свіжих фактів: курсів, цін, сьогоднішніх новин, результатів. Тоді чесно кажи, що без пошуку не знаєш, і підказуй команду. Коли ж питають твою думку, ставлення чи реакцію, навіть про поточні події — відповідай як є, з того, що знаєш, і не відсилай по команду.",
    );
  } else {
    abilities.push("- В інтернет не ходиш: свіжих новин і курсів не знаєш.");
  }
  abilities.push(
    "- Гіфки і стікери: «Кицюня, запиши як назва.гіф» у відповідь на гіфку — потім на слово «назва.гіф» ти її надсилаєш. Так само «.стікер». «Кицюня, забудь назва.гіф» видаляє, «Кицюня, які знаєш гіфки?» / «які знаєш стікери?» показує список.",
    "- Профілі: ти вивчаєш стиль учасників. «Кицюня, забудь мене» це вимикає, «Кицюня, запамʼятай мене» вмикає, «Кицюня, ти мене знаєш?» показує статус.",
    "- Ще команди: «Кицюня, де тривога?» — карта тривог; «Кицюня, виховуй» у відповідь на повідомлення — виховуєш; «Кицюня, скільки в мене лишилось?» — залишок добового ліміту звернень до тебе.",
    "- Команди спрацьовують автоматично, ще до того, як текст доходить до тебе. Якщо питають, як щось зробити — підкажи команду. Не обіцяй зробити те, чого без команди не вмієш: не надсилаєш гіфок з власної волі, не шукаєш без «пошукай», не ставиш нагадувань, не пишеш в інші чати.",
  );

  return `${opts.character ?? PERSONA_PROMPT}

Хто ти технічно:
${identity.join("\n")}

Що ти вмієш і чого не вмієш:
${abilities.join("\n")}`;
}

/**
 * Дописує спеціальні інструкції адміна в кінець промпту. Для відповідей це той
 * самий кешований блок, що й персона: інструкції змінюються рідко, а кеш
 * перебудовується лише при зміні списку. Вони мають пріоритет над базовими
 * правилами — інакше немає сенсу їх давати.
 */
export function withSpecialInstructions(prompt: string, instructions: readonly string[]): string {
  if (instructions.length === 0) return prompt;
  const lines = instructions.map((t) => `- ${t.trim().replace(/\n/g, "\n  ")}`);
  return `${prompt}\n\nСпеціальні інструкції від адміна для цього чату. Якщо вони суперечать правилам вище — виконуй інструкції:\n${lines.join("\n")}`;
}

