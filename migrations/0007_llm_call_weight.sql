-- Дайджест читає сотні повідомлень — один такий виклик коштує як десяток
-- звичайних реплаїв. Ліміти рахували COUNT(*), тобто «Кицюня, ти жива?» і
-- дайджест важили однаково. Тепер ліміт рахується як SUM(weight).
-- Старим рядкам DEFAULT 1 повертає попередню поведінку.
ALTER TABLE llm_calls ADD COLUMN weight INTEGER NOT NULL DEFAULT 1;
